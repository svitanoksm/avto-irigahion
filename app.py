@st.cache_data(ttl=60)
def load_data():

    SCOPES = [
        "https://www.googleapis.com/auth/spreadsheets.readonly",
        "https://www.googleapis.com/auth/drive.readonly"
    ]

    # --------------------------------------------------------
    # Авторизація Google
    # --------------------------------------------------------

    creds_dict = dict(
        st.secrets["gcp_service_account"]
    )

    creds = Credentials.from_service_account_info(
        creds_dict,
        scopes=SCOPES
    )

    client = gspread.authorize(creds)

    # --------------------------------------------------------
    # Відкриваємо таблицю
    # --------------------------------------------------------

    spreadsheet = client.open(
        SPREADSHEET_NAME
    )

    # --------------------------------------------------------
    # Відкриваємо аркуш
    # --------------------------------------------------------

    sheet = spreadsheet.worksheet(
        WORKSHEET_NAME
    )

    # ========================================================
    # ОТРИМУЄМО ФОРМАТОВАНІ ЗНАЧЕННЯ
    #
    # Тобто саме те, що бачимо в Google Sheets:
    #
    # 10,75
    # 12,16
    # 11,82
    #
    # а не внутрішнє представлення числа.
    # ========================================================

    values = sheet.get_all_values(
        value_render_option="FORMATTED_VALUE"
    )

    if not values:
        return pd.DataFrame()

    # --------------------------------------------------------
    # Перший рядок — заголовки
    # --------------------------------------------------------

    headers = values[0]

    # --------------------------------------------------------
    # Решта — дані
    # --------------------------------------------------------

    rows = values[1:]

    # --------------------------------------------------------
    # Створюємо DataFrame
    # --------------------------------------------------------

    df = pd.DataFrame(
        rows,
        columns=headers
    )

    # ========================================================
    # ПЕРЕТВОРЕННЯ ДАТИ
    # ========================================================

    if "Дата та час" in df.columns:

        df["Дата та час"] = pd.to_datetime(
            df["Дата та час"],
            errors="coerce"
        )

    # ========================================================
    # ПЕРЕТВОРЕННЯ ЧИСЛОВИХ СТОВПЧИКІВ
    # ========================================================

    numeric_columns = [

        "Потужність за період, кВт/год",

        "Продуктивність, куб. м./год",

        "Витрати, кВт",

        "Витрати, куб. м."
    ]

    for column in numeric_columns:

        if column in df.columns:

            df[column] = df[column].apply(
                convert_to_number
            )

    # ========================================================
    # СОРТУВАННЯ ЗА ДАТОЮ
    # ========================================================

    if "Дата та час" in df.columns:

        df = df.sort_values(
            by="Дата та час"
        )

        df = df.reset_index(
            drop=True
        )

    return df


